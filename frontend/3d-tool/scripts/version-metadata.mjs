#!/usr/bin/env node
// Same idea as frontend/uberflussigen/scripts/version-metadata.mjs: package.json is the source of the version;
// src/app/build-info.ts (shown in the header) and ngsw-config.json appData (shown on the "update available" button) follow it.
import fs from 'node:fs';
import path from 'node:path';

export function syncVersionMetadata(appRoot, log = console.log) {
  const { version } = JSON.parse(fs.readFileSync(path.join(appRoot, 'package.json'), 'utf8'));
  const buildDate = new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });

  fs.writeFileSync(
    path.join(appRoot, 'src', 'app', 'build-info.ts'),
    `// Auto-generated by scripts/version-metadata.mjs (npm run bump:version) - do not edit manually\n` +
      `export const APP_VERSION = '${version}';\nexport const BUILD_DATE = '${buildDate}';\n`,
    'utf8',
  );
  log(`build-info.ts written: v${version} · ${buildDate}`);

  const ngswPath = path.join(appRoot, 'ngsw-config.json');
  const ngsw = JSON.parse(fs.readFileSync(ngswPath, 'utf8'));
  ngsw.appData = { version };
  fs.writeFileSync(ngswPath, JSON.stringify(ngsw, null, 2) + '\n', 'utf8');
  log(`ngsw-config.json appData.version: ${version}`);

  // the Fusion add-in (../../fusion-addin) carries the app's version too: Fusion shows it in the Version column of Scripts and Add-Ins
  const manifestPath = path.join(appRoot, '..', '..', 'fusion-addin', 'AddInRasterfasterLocalF3D', 'AddInRasterfasterLocalF3D.manifest');
  if (fs.existsSync(manifestPath)) {
    const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    manifest.version = version;
    fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n', 'utf8');
    log(`Fusion add-in manifest version: ${version}`);
  }
  return { version, buildDate };
}
